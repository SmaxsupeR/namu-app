/** "인간 > 감정" → "Чувства"; "인간" → "Человек". */
export function topicName(topic: string): string {
  return TOPIC_RU[topic] ?? topic.split(' > ').pop() ?? topic;
}

export function subjectName(subject: string): string {
  return SUBJECT_RU[subject] ?? subject;
}

/** Top-level topics in a stable order. */
